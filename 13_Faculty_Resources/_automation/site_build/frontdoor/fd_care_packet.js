/* The days since the directory copy was made, when that is more than a week; otherwise null. The current time is passed in so the
   answer is a pure function of its inputs. */
function fdCarePacketStale(generatedAt,now){
  var m=/^(\d{4})-(\d{2})-(\d{2})/.exec(typeof generatedAt==='string'?generatedAt:''),days;
  if(!m||typeof now!=='number'||!isFinite(now))return null;
  days=Math.floor((now-Date.UTC(Number(m[1]),Number(m[2])-1,Number(m[3])))/86400000);
  return days>FD_CARE_PACKET_STALE_DAYS?{days:days,date:m[1]+'-'+m[2]+'-'+m[3]}:null;
}
