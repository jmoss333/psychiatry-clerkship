def _breakdown(document):
    counts = {}
    for page in document["pages"]:
        counts[page["producer"]] = counts.get(page["producer"], 0) + 1
    return ", ".join("%d %s" % (count, name) for name, count in sorted(counts.items()))


def write(root=ROOT):
    document = derive(root)
    path = os.path.join(root, RELATIVE_PATH)
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(serialize(document))
    print(
        "shipped_pages.json written — %d page(s): %s"
        % (len(document["pages"]), _breakdown(document))
    )
    return 0


def check(root=ROOT):
    """Regenerate in memory and diff against the tracked file."""
    expected = serialize(derive(root))
    path = os.path.join(root, RELATIVE_PATH)
    try:
        with open(path, encoding="utf-8") as handle:
            actual = handle.read()
    except OSError as error:
        print("shipped_pages.json STALE — cannot read the tracked file: %s" % error)
        print("Regenerate it:  %s" % WRITE_COMMAND)
        return 1
    if actual == expected:
        document = json.loads(actual)
        print(
            "shipped_pages OK — %d page(s) derived from the producers: %s"
            % (len(document["pages"]), _breakdown(document))
        )
        return 0
    print("shipped_pages.json STALE — a producer changed and the tracked file did not.")
    print("Regenerate it:  %s" % WRITE_COMMAND)
    print()
    for line in difflib.unified_diff(
        actual.splitlines(keepends=True),
        expected.splitlines(keepends=True),
        fromfile="shipped_pages.json (tracked)",
        tofile="shipped_pages.json (derived)",
    ):
        sys.stdout.write(line)
    return 1


def built_slugs(out_dir):
    """What a finished build actually publishes: content/*.md + tools/*.html.

    Everything else under tools/ (packs, vendored JS, media) is an asset that
    rides along with a tool, not a page anyone attests.
    """
    out_dir = os.fspath(out_dir).rstrip("/\\")
    found = {
        os.path.basename(p) for p in glob.glob(os.path.join(out_dir, "content", "*.md"))
    }
    found |= {
        os.path.basename(p) for p in glob.glob(os.path.join(out_dir, "tools", "*.html"))
    }
    return found


def check_build(out_dir, site, root=ROOT):
    """THE structural guarantee: the tracked listing equals the real build.

    A disagreement in either direction fails the build. That is what makes this
    a derivation from reality rather than a second thing to remember.
    """
    if site not in SITES:
        print("unknown site %r (expected ms3|res)" % site)
        return 2
    if not os.path.isdir(out_dir):
        print("shipped_pages --check-build: %s is not a build directory" % out_dir)
        return 2
    try:
        document = load_shipped_pages(root)
    except ShippedPagesError as error:
        print("shipped_pages --check-build INVALID — %s" % error)
        return 1

    expected = slugs_for_site(document, site)
    actual = built_slugs(out_dir)
    only_tracked = sorted(expected - actual)
    only_built = sorted(actual - expected)
    if not only_tracked and not only_built:
        print(
            "shipped_pages --check-build OK — %s publishes exactly the %d tracked slug(s)"
            % (site, len(expected))
        )
        return 0

    print(
        "shipped_pages --check-build FAILED — %s: %d tracked slug(s) not built, "
        "%d built slug(s) not tracked." % (site, len(only_tracked), len(only_built))
    )
    for slug in only_tracked:
        print(
            "  - %s: shipped_pages.json says %s ships it; the build did not produce it"
            % (slug, site)
        )
    for slug in only_built:
        print(
            "  + %s: the %s build published it and shipped_pages.json does not list it. "
            "A page that ships must be attestable — wire its producer into "
            "site_build/shipped_pages.py, then run: %s" % (slug, site, WRITE_COMMAND)
        )
    return 1


def main(argv=None):
    parser = argparse.ArgumentParser(description="Derive and gate shipped_pages.json.")
    parser.add_argument("--root", default=ROOT, help="repository root")
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true", help="regenerate the tracked file")
    group.add_argument("--check", action="store_true", help="fail if the tracked file is stale")
    group.add_argument(
        "--check-build",
        metavar="OUT",
        help="fail if the tracked file disagrees with a finished build directory",
    )
    parser.add_argument("--site", choices=SITES, help="which site --check-build is verifying")
    args = parser.parse_args(argv)

    root = os.path.abspath(args.root)
    try:
        if args.write:
            return write(root)
        if args.check:
            return check(root)
        if not args.site:
            parser.error("--check-build requires --site ms3|res")
        return check_build(args.check_build, args.site, root)
    except ShippedPagesError as error:
        print("shipped_pages INVALID — %s" % error)
        return 1


if __name__ == "__main__":
    sys.exit(main())
