#!/usr/bin/env python3
"""evidence_excerpts.py -- the learner index behind "In the paper's own words".

WHY THIS EXISTS
A reference list tells a learner WHICH paper a page leans on. It does not show what the paper
actually says, and on a phone between patients nobody opens the PDF. The library already holds
that text: every source in evidence_annotations.json carries a verbatim `sourceSpan` that
validate_evidence_annotations.py checks the library's claims against (CLAUDE.md invariant 9).
This module projects those spans into a small read-only index the reader uses to put the
paper's own words, collapsed, under the reference that cites it.

WHAT IT NEVER DOES
It writes no teaching text. The index carries the verbatim span, its kind and the date it was
checked against the source -- never the library's `claimText`, which is the library's
paraphrase and belongs to the page under faculty review. It never reads a page and never edits
the registry: evidence_annotations.json is the single source, and a corrected span reaches the
learner on the next build with no second copy to keep in step.

SHAPE (schemaVersion 1)
  {"schemaVersion": 1,
   "sources": {sourceId: {"span": str, "spanType": str, "checked": "YYYY-MM-DD"}},
   "byPmid":  {pmid: sourceId},
   "byDoi":   {lower-cased doi: sourceId}}

A source with no span, or an identifier claimed by two sources, is left out of the lookup
rather than guessed: showing a learner the wrong paper's words is worse than showing none.

Usage:
  python3 evidence_excerpts.py --out DIR      # write DIR/evidence_excerpts.json
  python3 evidence_excerpts.py --stdout       # print the index
  python3 evidence_excerpts.py --from FILE --stdout   # derive from another annotations file
                                                      # (tests/fd-ref-evidence.test.mjs fixtures)
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
LIB = HERE.parents[2]
ANNOTATIONS = LIB / "evidence_annotations.json"
FILENAME = "evidence_excerpts.json"

PMID_RE = re.compile(r"^\d{5,9}$")
DOI_RE = re.compile(r"^10\.\d{4,9}/\S+$")
DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
SPAN_TYPES = {"abstract", "fulltext", "guideline-statement", "conclusion"}


def normalize_doi(raw: str) -> str:
    """Lower-case a DOI and strip a resolver prefix and trailing punctuation."""
    doi = (raw or "").strip()
    doi = re.sub(r"^(?:https?://(?:dx\.)?doi\.org/|doi:\s*)", "", doi, flags=re.I)
    return doi.rstrip(".,;)").lower()


def derive(document: dict) -> dict:
    """Project evidence_annotations.json into the learner excerpt index. Pure."""
    annotations = document.get("annotations")
    if not isinstance(annotations, list):
        raise ValueError("evidence_annotations.json: `annotations` must be a list")
    sources: dict[str, dict] = {}
    pmid_owners: dict[str, set[str]] = {}
    doi_owners: dict[str, set[str]] = {}
    for row in annotations:
        sid = row.get("sourceId")
        verified = row.get("verifiedAgainst") or {}
        span = " ".join(str(verified.get("sourceSpan") or "").split())
        if not isinstance(sid, str) or not sid or not span:
            continue
        span_type = verified.get("spanType")
        checked = verified.get("retrievedAt")
        sources[sid] = {
            "span": span,
            "spanType": span_type if span_type in SPAN_TYPES else "excerpt",
            "checked": checked if isinstance(checked, str) and DATE_RE.match(checked) else "",
        }
        pmid = str(verified.get("pmid") or "").strip()
        if PMID_RE.match(pmid):
            pmid_owners.setdefault(pmid, set()).add(sid)
        doi = normalize_doi(str(verified.get("doi") or ""))
        if DOI_RE.match(doi):
            doi_owners.setdefault(doi, set()).add(sid)

    def unique(owners: dict[str, set[str]]) -> dict[str, str]:
        return {key: next(iter(ids)) for key, ids in sorted(owners.items()) if len(ids) == 1}

    return {
        "schemaVersion": 1,
        "_note": "Generated by site_build/evidence_excerpts.py from evidence_annotations.json. "
                 "Verbatim source spans only; never edit by hand.",
        "sources": {sid: sources[sid] for sid in sorted(sources)},
        "byPmid": unique(pmid_owners),
        "byDoi": unique(doi_owners),
    }


def load(path: Path = ANNOTATIONS) -> dict:
    return derive(json.loads(path.read_text(encoding="utf-8")))


def write(out_dir: str | Path, path: Path = ANNOTATIONS) -> Path:
    target = Path(out_dir) / FILENAME
    target.write_text(json.dumps(load(path), ensure_ascii=False, separators=(",", ":")),
                      encoding="utf-8")
    return target


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", help="directory to write %s into" % FILENAME)
    parser.add_argument("--stdout", action="store_true")
    parser.add_argument("--from", dest="source", default=str(ANNOTATIONS),
                        help="annotations file to derive from (default: evidence_annotations.json)")
    args = parser.parse_args(argv)
    source = Path(args.source)
    if args.stdout:
        print(json.dumps(load(source), ensure_ascii=False, indent=1))
        return 0
    if args.out:
        print("wrote", write(args.out, source))
        return 0
    parser.print_help()
    return 2


if __name__ == "__main__":
    sys.exit(main())
