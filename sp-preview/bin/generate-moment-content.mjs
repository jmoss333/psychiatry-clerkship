import {readFile,writeFile} from 'node:fs/promises';
import {pathToFileURL} from 'node:url';
import {getMoment,momentIds,publicProjection} from '../lib/moments/catalog.mjs';

const output = new URL('../public/moment-content.js',import.meta.url);
export function renderContent(){
 const profiles=Object.fromEntries([...momentIds].sort().map(id=>[id,publicProjection(getMoment(id))]));
 return `/* Generated by bin/generate-moment-content.mjs; edit the authored catalog, then --write. */
(function(root){
  'use strict';
  function freeze(value){
    if(value && typeof value==='object' && !Object.isFrozen(value)){
      Object.keys(value).forEach(function(key){freeze(value[key]);});
      Object.freeze(value);
    }
    return value;
  }
  var profiles=freeze(${JSON.stringify(profiles,null,2)});
  var api=Object.freeze({
    getProfile:function(id){return typeof id==='string' && Object.prototype.hasOwnProperty.call(profiles,id)?profiles[id]:undefined;},
    ids:function(){return Object.freeze(Object.keys(profiles));}
  });
  if(typeof module==='object' && module.exports){module.exports=api;}
  else{root.MomentContent=api;}
})(typeof globalThis!=='undefined'?globalThis:this);
`;
}
export async function checkGenerated(path=output){
 try{return await readFile(path,'utf8')===renderContent();}
 catch(error){if(error.code==='ENOENT')return false;throw error;}
}
async function main(){
 const args=process.argv.slice(2);
 if(args.length!==1||!['--write','--check'].includes(args[0])){
  console.error('Usage: node sp-preview/bin/generate-moment-content.mjs --write|--check');process.exitCode=2;return;
 }
 if(args[0]==='--write'){
  await writeFile(output,renderContent(),'utf8');console.log('Wrote sp-preview/public/moment-content.js');
 }else if(!await checkGenerated()){
  console.error('Moment public projection is stale. Run node sp-preview/bin/generate-moment-content.mjs --write.');process.exitCode=1;
 }else console.log('Moment public projection is current.');
}
if(process.argv[1]&&pathToFileURL(process.argv[1]).href===import.meta.url)await main();
